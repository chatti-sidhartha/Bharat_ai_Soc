package com.example.learnedge.data.content

import android.content.res.AssetManager
import com.example.learnedge.domain.BankQuestion
import com.example.learnedge.domain.TopicContent
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

/** Hand-written content of one track, read from one assets/content_*.json file. */
data class TrackContent(val trackId: String, val topics: List<TopicContent>)

/** Reads the bundled lesson key points and question bank. No Android dependencies, so it is unit-tested on the JVM. */
object ContentParser {
    private val json = Json { ignoreUnknownKeys = false }

    fun parse(text: String): TrackContent {
        val file = json.decodeFromString<ContentFile>(text)
        val topics = file.topics.map { t ->
            TopicContent(
                topicId = t.topicId,
                keyPoints = t.keyPoints,
                questions = t.questions.map { BankQuestion(it.id, t.topicId, it.question, it.options, it.answerIndex, it.explanation) },
            )
        }
        val duplicateTopics = topics.groupBy { it.topicId }.filterValues { it.size > 1 }.keys
        require(duplicateTopics.isEmpty()) { "Duplicate topic ids in content file ${file.track}: $duplicateTopics" }
        val duplicateQuestions = topics.flatMap { it.questions }.groupBy { it.id }.filterValues { it.size > 1 }.keys
        require(duplicateQuestions.isEmpty()) { "Duplicate question ids in content file ${file.track}: $duplicateQuestions" }
        return TrackContent(file.track, topics)
    }
}

@Serializable
private data class ContentFile(val track: String, val topics: List<TopicJson>)

@Serializable
private data class TopicJson(val topicId: String, val keyPoints: List<String>, val questions: List<QuestionJson>)

@Serializable
private data class QuestionJson(
    val id: String,
    val question: String,
    val options: List<String>,
    val answerIndex: Int,
    val explanation: String = "",
)

/** The bundled content is fixed and hand-written, so it is always available offline and never generated by the LLM. */
class ContentRepository(private val assets: AssetManager) {
    @Volatile private var cached: Map<String, TopicContent>? = null

    suspend fun content(topicId: String): TopicContent? = all()[topicId]

    suspend fun all(): Map<String, TopicContent> = cached ?: withContext(Dispatchers.IO) {
        ASSETS.flatMap { name -> ContentParser.parse(assets.open(name).bufferedReader().use { it.readText() }).topics }
            .associateBy { it.topicId }
    }.also { cached = it }

    companion object {
        val ASSETS = listOf("content_java-backend.json", "content_dsa.json")
    }
}
